# packaging/manifests.sh VERSION SHA256 — write Formula/anzen.rb (Homebrew)
# and bucket/anzen.json (Scoop) for the release tarball anzen-VERSION.tar.gz
# with that SHA-256. The release workflow runs it after each release.
set -euo pipefail

VERSION=${1:?usage: packaging/manifests.sh VERSION SHA256}
SHA=${2:?usage: packaging/manifests.sh VERSION SHA256}
[[ "$VERSION" =~ ^[0-9]+\.[0-9]+\.[0-9]+$ ]] || { echo "ERROR: bad version '$VERSION'" >&2; exit 1; }
[[ "$SHA" =~ ^[0-9a-f]{64}$ ]] || { echo "ERROR: bad sha256 '$SHA'" >&2; exit 1; }
ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
URL="https://github.com/anzen-d/anzen/releases/download/v$VERSION/anzen-$VERSION.tar.gz"
mkdir -p "$ROOT/Formula" "$ROOT/bucket"

cat > "$ROOT/Formula/anzen.rb" <<RUBY
# Generated by packaging/manifests.sh — do not edit by hand.
# brew tap anzen-d/anzen https://github.com/anzen-d/anzen && brew install anzen
class Anzen < Formula
  desc "Security audit for macOS, Linux and Windows hosts"
  homepage "https://github.com/anzen-d/anzen"
  url "$URL"
  sha256 "$SHA"
  license "AGPL-3.0-or-later"

  def install
    libexec.install Dir["*"]
    # macOS edition on a Mac, the Linux edition under Homebrew on Linux
    script = OS.mac? ? "macos/anzen-macos.sh" : "anzen.sh"
    (bin/"anzen").write <<~SH
      #!/bin/bash
      exec /bin/bash "#{libexec}/#{script}" "\$@"
    SH
    chmod 0755, bin/"anzen"
  end

  test do
    assert_match version.to_s, shell_output("#{bin}/anzen --version")
  end
end
RUBY

cat > "$ROOT/bucket/anzen.json" <<JSON
{
    "version": "$VERSION",
    "description": "Security audit for Windows hosts (PowerShell edition of anzen)",
    "homepage": "https://github.com/anzen-d/anzen",
    "license": "AGPL-3.0-or-later",
    "url": "$URL",
    "hash": "$SHA",
    "extract_dir": "anzen-$VERSION",
    "bin": [["windows\\\\anzen.ps1", "anzen"]],
    "notes": "Run from an elevated PowerShell for complete results: anzen -Html",
    "checkver": "github",
    "autoupdate": {
        "url": "https://github.com/anzen-d/anzen/releases/download/v\$version/anzen-\$version.tar.gz",
        "extract_dir": "anzen-\$version",
        "hash": { "url": "\$url.sha256" }
    }
}
JSON
echo "Formula/anzen.rb and bucket/anzen.json for $VERSION"
