# lib/fleet.sh — Audit remote hosts over SSH (--remote=host1,host2,...)
# Linux hosts run anzen.sh, macOS hosts (uname -s = Darwin) macos/anzen-macos.sh,
# Windows hosts (OpenSSH server, no uname) windows/anzen.ps1.
#
# Per host: copy anzen to a remote mktemp dir with a generated anzen.conf that
# carries only scan settings (thresholds, excludes, CVE/image options) and the
# local accept file; run it with --json; fetch the JSON; remove the dir. Then,
# locally: store the JSON in HISTORY_DIR/<host>/, notify per host (NOTIFY_ON),
# rebuild the dashboard once and send one heartbeat. History, notification and
# dashboard settings never leave this machine.

# Scan settings shipped to remote hosts (see config.sh)
_FLEET_KEYS="DISK_WARN_PCT DISK_FAIL_PCT MEM_WARN_PCT MEM_FAIL_PCT FAIL_LOGIN_OK FAIL_LOGIN_WARN
SERVICE_COUNT_WARN SERVICE_COUNT_FAIL PASS_MAX_DAYS_WARN TLS_WARN_DAYS TLS_FAIL_DAYS
SCORE_FAIL_PENALTY SCORE_WARN_PENALTY EXCLUDE_CHECKS CUSTOM_SUID_WHITELIST EXCLUDE_PATHS
WW_FILE_CAP FAIL_AS_WARN CVE_SEVERITY CVE_IGNORE_UNFIXED CVE_SCAN_IMAGES CVE_TIMEOUT
CVE_SKIP_DIRS IMAGE_MAX_AGE_DAYS IMAGE_CHECK_UPDATES IMAGE_WARN_LATEST TRUSTSTORE_SCAN_CONTAINERS
CVE_NEW_DAYS KEV_CHECK KEV_URL"

# ANZEN_SSH overrides the ssh binary (tests use a local stand-in)
_FLEET_SSH=("${ANZEN_SSH:-ssh}" -o BatchMode=yes -o ConnectTimeout=10)

_fleet_conf() {
    local k
    echo "# Generated by anzen --remote on $(_hostname) — scan settings only"
    for k in $_FLEET_KEYS; do
        [ -n "${!k+x}" ] && printf '%s=%q\n' "$k" "${!k}"
    done
}

# _fleet_json_field FILE KEY — top-level string value from a JSON report
_fleet_json_field() { sed -n "s/^  \"$2\": \"\\(.*\\)\",\$/\\1/p" "$1" | head -1; }

# Report formats requested locally, as remote file extensions (json always)
_fleet_formats() {
    echo json
    ${GENERATE_HTML:-false}  && echo html
    ${GENERATE_TXT:-false}   && echo txt
    ${GENERATE_SARIF:-false} && echo sarif.json
    ${GENERATE_CSV:-false}   && echo csv
}

# Windows hosts: the OpenSSH server starts cmd.exe or PowerShell, so every
# command is a PowerShell -EncodedCommand (UTF-16LE base64: no quoting issues
# in either shell). Files go in and reports come back as "name<TAB>base64" lines
_fleet_ps_encode() { iconv -f UTF-8 -t UTF-16LE | base64 | tr -d '\n'; }

_fleet_is_windows() {
    local enc out
    enc=$(printf '%s' '[Console]::Out.WriteLine([Environment]::OSVersion.Platform)' | _fleet_ps_encode)
    out=$("${_FLEET_SSH[@]}" "$1" "powershell -NoProfile -NonInteractive -EncodedCommand $enc" 2>/dev/null)
    [ "${out%$'\r'}" = Win32NT ]
}

# Runs on the Windows host: write the files from stdin to a temp dir, audit
# with the requested formats, print the reports and the exit code, clean up
# shellcheck disable=SC2016
# (No ErrorActionPreference=Stop: PowerShell 5.1 would turn stderr of the
# redirected inner run into a terminating error.)
_FLEET_PS_BOOTSTRAP='$d = Join-Path ([IO.Path]::GetTempPath()) ("anzen." + [guid]::NewGuid().ToString("N").Substring(0, 12))
try {
    foreach ($l in ([Console]::In.ReadToEnd() -split "`n")) {
        if ($l -notmatch "^(windows/anzen\.ps1|windows/anzen\.accept|lib/data/[a-z-]+\.tsv)\t([A-Za-z0-9+/=]*)\r?$") { continue }
        $p = Join-Path $d ($Matches[1] -replace "/", "\")
        New-Item -ItemType Directory -Force -Path (Split-Path -Parent $p) | Out-Null
        [IO.File]::WriteAllBytes($p, [Convert]::FromBase64String($Matches[2]))
    }
    $a = @("-NoProfile", "-NonInteractive", "-ExecutionPolicy", "Bypass", "-File", (Join-Path $d "windows\anzen.ps1"),
           "-Quiet", "-Offline", "-Output", (Join-Path $d "out.json"))
    $f = "@FORMATS@" -split ","
    foreach ($x in $f) { switch ($x) { "json" { $a += "-Json" } "html" { $a += "-Html" } "txt" { $a += "-Txt" } "sarif.json" { $a += "-Sarif" } "csv" { $a += "-Csv" } } }
    if ("@CHECKS@") { $a += "-Check"; $a += "@CHECKS@" }
    if ("@STRICT@" -eq "1") { $a += "-Strict" }
    & powershell.exe @a *> $null
    $rc = $LASTEXITCODE
    foreach ($x in $f) {
        $p = Join-Path $d "out.$x"
        if (Test-Path -LiteralPath $p) { [Console]::Out.WriteLine("$x`t" + [Convert]::ToBase64String([IO.File]::ReadAllBytes($p))) }
    }
    [Console]::Out.WriteLine("rc`t$rc")
} finally { Remove-Item -LiteralPath $d -Recurse -Force -ErrorAction SilentlyContinue }'

# _fleet_run_windows HOST WORKDIR ARGS... — like _fleet_run_host for Windows;
# passes on --check (module names only) and --strict
_fleet_run_windows() {
    local host=$1 work=$2; shift 2
    local a c checks="" strict=0 formats ps f name b64 rc=255
    for a in "$@"; do
        case $a in
            --check=*) c=${a#--check=}
                       [[ $c =~ ^[a-z0-9_,]+$ ]] && checks+="${checks:+,}$c" ;;
            --strict)  strict=1 ;;
        esac
    done
    formats=$(_fleet_formats | paste -sd, -)
    ps=${_FLEET_PS_BOOTSTRAP//@FORMATS@/$formats}
    ps=${ps//@CHECKS@/$checks}
    ps=${ps//@STRICT@/$strict}
    while IFS=$'\t' read -r name b64; do
        b64=${b64%$'\r'}
        case $name in
            rc) [[ $b64 =~ ^[0-9]+$ ]] && rc=$b64 ;;
            json|html|txt|sarif.json|csv) printf '%s' "$b64" | base64 -d > "$work/out.$name" 2>/dev/null ;;
        esac
    done < <({
        for f in windows/anzen.ps1 lib/data/distrusted-certs.tsv lib/data/controls.tsv lib/data/ioc.tsv; do
            [ -f "$ANZEN_DIR/$f" ] && printf '%s\t%s\n' "$f" "$(base64 < "$ANZEN_DIR/$f" | tr -d '\n')"
        done
        if [ -n "${ACCEPT_FILE:-}" ] && [ -f "$ACCEPT_FILE" ]; then
            printf 'windows/anzen.accept\t%s\n' "$(base64 < "$ACCEPT_FILE" | tr -d '\n')"
        fi
    } | "${_FLEET_SSH[@]}" "$host" "powershell -NoProfile -NonInteractive -EncodedCommand $(printf '%s' "$ps" | _fleet_ps_encode)")
    [ -s "$work/out.json" ] || { echo "ERROR: $host: no JSON report produced" >&2; return 255; }
    return "$rc"
}

# _fleet_run_host HOST WORKDIR ARGS... — run anzen on HOST; its reports land in
# WORKDIR/out.<ext>. Returns the remote anzen exit code (255 on SSH/setup failure)
_fleet_run_host() {
    local host=$1 work=$2; shift 2
    local tmp rc
    # macOS hosts run the macOS edition (Bash 3.2, its own modules), which
    # takes only these flags; Windows has no uname
    local os; os=$("${_FLEET_SSH[@]}" "$host" "uname -s" 2>/dev/null)
    local ed=""
    if [ -z "$os" ] && _fleet_is_windows "$host"; then ed=windows/anzen.ps1
    elif [ "$os" = Darwin ]; then ed=macos/anzen-macos.sh; fi
    if [ -n "$ed" ] && [ ! -f "$ANZEN_DIR/$ed" ]; then
        echo "ERROR: $host: $ANZEN_DIR/$ed is missing (needed for this host's OS)" >&2
        return 255
    fi
    if [ "$ed" = windows/anzen.ps1 ]; then
        _fleet_run_windows "$host" "$work" "$@"
        return
    fi
    tmp=$("${_FLEET_SSH[@]}" "$host" "mktemp -d /tmp/anzen.XXXXXX" 2>/dev/null)
    # Validate mktemp output before embedding it in remote shell commands
    if [[ ! "$tmp" =~ ^/tmp/anzen\.[a-zA-Z0-9]+$ ]]; then
        echo "ERROR: $host: could not create a remote temp dir" >&2
        return 255
    fi
    local qtmp; qtmp=$(printf '%q' "$tmp")

    tar -czf - -C "$ANZEN_DIR" --exclude=./reports --exclude=./anzen.conf --exclude=./anzen.accept \
            --exclude=./.git . \
        | "${_FLEET_SSH[@]}" "$host" "umask 077 && tar -xzf - -C $qtmp" || {
        echo "ERROR: $host: copy failed" >&2; return 255; }
    _fleet_conf | "${_FLEET_SSH[@]}" "$host" "umask 077 && cat > $qtmp/anzen.conf"
    if [ -n "${ACCEPT_FILE:-}" ] && [ -f "$ACCEPT_FILE" ]; then
        "${_FLEET_SSH[@]}" "$host" "umask 077 && cat > $qtmp/anzen.accept" < "$ACCEPT_FILE"
    fi

    local -a qargs=()
    local a
    for a in "$@"; do
        if [ "$os" = Darwin ]; then
            case $a in --check=*|--strict|--quiet|-q|--no-color) ;; *) continue ;; esac
        fi
        qargs+=("$(printf '%q' "$a")")
    done
    local ext fmt_flags=""
    for ext in $(_fleet_formats); do
        case $ext in json) fmt_flags+=" --json" ;; html) fmt_flags+=" --html" ;;
                     txt) fmt_flags+=" --txt" ;; sarif.json) fmt_flags+=" --sarif" ;;
                     csv) fmt_flags+=" --csv" ;; esac
    done
    # Several formats + --output=out.json → out.json, out.html, ... (extension swap)
    if [ "$os" = Darwin ]; then
        local run="/bin/bash $qtmp/macos/anzen-macos.sh$fmt_flags --output=$qtmp/out.json ${qargs[*]:-}"
        # Root gives complete results: use passwordless sudo when the login is not root
        "${_FLEET_SSH[@]}" "$host" \
            "if [ \"\$(id -u)\" -ne 0 ] && sudo -n true 2>/dev/null; then sudo -n $run; else $run; fi"
    else
        "${_FLEET_SSH[@]}" "$host" \
            "bash $qtmp/anzen.sh$fmt_flags --output=$qtmp/out.json ${qargs[*]:-}"
    fi
    rc=$?
    for ext in $(_fleet_formats); do
        "${_FLEET_SSH[@]}" "$host" "cat $qtmp/out.$ext" > "$work/out.$ext" 2>/dev/null
    done
    "${_FLEET_SSH[@]}" "$host" "rm -rf $qtmp"
    [ -s "$work/out.json" ] || { echo "ERROR: $host: no JSON report produced" >&2; return 255; }
    return "$rc"
}

# run_fleet HOSTS ARGS... — HOSTS comma-separated [user@]host; prints per-host
# results and returns the worst exit code (255 > 2 > 1 > 0)
run_fleet() {
    local hosts=$1; shift
    local -a list
    IFS=',' read -ra list <<< "$hosts"

    local h worst=0 rc work json name prev new nf score ext dest
    for h in "${list[@]}"; do
        # Reject anything that isn't [user@]hostname with safe characters only
        if [[ ! "$h" =~ ^([a-zA-Z0-9._-]+@)?[a-zA-Z0-9._-]+$ ]]; then
            echo "ERROR: Invalid --remote host '$h'" >&2
            worst=255; continue
        fi
    done
    [ "$worst" -eq 255 ] && return 255

    for h in "${list[@]}"; do
        echo -e "\n${BOLD}${CYAN}━━━ $h ━━━${NC}"
        work=$(umask 077; mktemp -d)
        json="$work/out.json"
        _fleet_run_host "$h" "$work" "$@"
        rc=$?
        if [ "$rc" -ne 255 ]; then
            name=$(_fleet_json_field "$json" hostname)
            name=${name:-${h#*@}}
            nf=$(sed -n 's/^  "summary": {"fail": \([0-9]*\),.*/\1/p' "$json")
            score=$(sed -n 's/.*"score": \([0-9]*\)}.*/\1/p' "$json" | head -1)
            new=""
            # PARTIAL_RUN (anzen.sh): --check runs stay out of history and alerts
            if [ -n "${HISTORY_DIR:-}" ] && ! ${PARTIAL_RUN:-false}; then
                prev=$(history_latest "$HISTORY_DIR" "$name")
                [ -n "$prev" ] && new=$(history_new_fails_json "$prev" "$json")
                history_store "$HISTORY_DIR" "$name" "$json" >/dev/null && \
                    echo -e "${BOLD}${CYAN}  History   : $(history_latest "$HISTORY_DIR" "$name")${NC}"
            fi
            # Requested reports: --output (one host; extension swapped when several
            # formats) or reports/anzen_<host>_<ts>.<ext>
            local -a saved=()
            for ext in $(_fleet_formats); do
                [ "$ext" = json ] && ! ${GENERATE_JSON:-false} && continue
                saved+=("$ext")
            done
            for ext in "${saved[@]}"; do
                [ -s "$work/out.$ext" ] || continue
                if [ "${#list[@]}" -eq 1 ] && [ -n "${OUTPUT_FILE:-}" ]; then
                    dest=$OUTPUT_FILE
                    [ "${#saved[@]}" -gt 1 ] && dest="${OUTPUT_FILE%.*}.$ext"
                else
                    mkdir -p "$REPORT_DIR"
                    dest="$REPORT_DIR/anzen_${name%%.*}_${TIMESTAMP}.$ext"
                fi
                cp "$work/out.$ext" "$dest" && echo -e "${BOLD}${CYAN}  Report    : $dest${NC}"
            done
            ${PARTIAL_RUN:-false} || notify_run "${nf:-0}" "${score:-0}" "$new" "$name"
        fi
        rm -rf "$work"
        case "$rc" in
            255) worst=255 ;;
            2)   [ "$worst" -lt 2 ] && worst=2 ;;
            1)   [ "$worst" -lt 1 ] && worst=1 ;;
        esac
    done

    ${PARTIAL_RUN:-false} && return "$worst"
    if [ -n "${HISTORY_DIR:-}" ] && [ -n "${DASHBOARD_FILE:-}" ]; then
        generate_dashboard "$HISTORY_DIR" "$DASHBOARD_FILE" && \
            echo -e "${BOLD}${CYAN}  Dashboard : $DASHBOARD_FILE${NC}"
    fi
    heartbeat
    return "$worst"
}
